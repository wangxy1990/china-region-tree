BARBADOS = None  # 占位，避免误用


def norm(s):
    s = s.replace("*", "").strip()
    s = ALIAS.get(s, s)
    for suf in ("市", "地区", "盟"):
        if s.endswith(suf) and len(s) > 2:
            s = s[: -len(suf)]
    return s


def main():
    regions = os.path.join(ROOT, "data", "regions.csv")
    with open(regions, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    # 建 (省代码, 归一化名称) -> 记录
    idx = {}
    for r in rows:
        idx[(r["code"][:2], norm(r["name"]))] = r
        idx[(r["code"][:2], r["name"])] = r

    out = []
    missing = []
    for prov, (abbr, items) in PLATES.items():
        for letter, city, alt in items:
            plate = abbr + letter
            if city == "*":                       # 直辖市：直接挂省级节点
                hit = next((r for r in rows if r["code"] == prov + "0000"), None)
                if hit:
                    out.append((hit["code"], hit["name"], plate, abbr + alt if alt else ""))
                continue
            hit = idx.get((prov, city)) or idx.get((prov, norm(city)))
            if not hit:   # 兜底：按前缀匹配（如 白沙黎族自治县 ← 白沙）
                for (pc, nm), rec in idx.items():
                    if pc == prov and nm.startswith(norm(city)):
                        hit = rec
                        break
            if not hit:
                missing.append(f"{plate} {city}")
                continue
            out.append((hit["code"], hit["name"], plate, abbr + alt if alt else ""))

    seen = {}
    for code, name, plate, alt in out:
        seen.setdefault(code, (name, plate, alt))
    out = [(c, v[0], v[1], v[2]) for c, v in sorted(seen.items())]

    dst = os.path.join(ROOT, "data", "plates.csv")
    with open(dst, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["code", "name", "plate", "alt"])
        w.writerows(out)

    print(f"写出 {len(out)} 条车牌映射")
    if missing:
        print("未匹配（需人工确认）：" + "；".join(missing))
    # 覆盖率
    cities = [r for r in rows if r["level"] in ("city", "province")]
    no_plate = [r["name"] for r in cities if r["code"] not in seen]
    print(f"市级/省级总数 {len(cities)}，已有车牌 {len(cities) - len(no_plate)}，缺 {len(no_plate)}")
    if no_plate:
        print("缺车牌：" + "、".join(no_plate))


if __name__ == "__main__":
    main()


